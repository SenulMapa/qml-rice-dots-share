#!/usr/bin/env python3

"""Zen browser theme injection from this shell's wallpaper palette.

Usage: repaint-zen.py PALETTE_JSON

PALETTE_JSON is this shell's own matugen-format palette (the file
generate-palette.sh writes: {"mode": "...", "dark": {...}, "light": {...}}).
Writes to <zen-profile>/chrome/userChrome.css, atomically; if the Zen profile
path or palette file are missing, exits 0 (side-effect-free, safe to run by
hand, never breaks the wallpaper pipeline).
"""

import configparser
import json
import os
import sys
import tempfile

XDG_CONFIG_HOME = os.environ.get("XDG_CONFIG_HOME") or os.path.expanduser("~/.config")
ZEN_PROFILES_INI = os.path.join(XDG_CONFIG_HOME, "zen", "profiles.ini")


def resolve_zen_profile_path():
    """Resolve Zen's default profile directory from profiles.ini.

    Returns the absolute path to the profile directory, or None if not found.
    The Default= entry is under the [Install<...>] section and points to a
    relative path (relative to ~/.config/zen).
    """
    if not os.path.exists(ZEN_PROFILES_INI):
        return None

    config = configparser.ConfigParser()
    try:
        config.read(ZEN_PROFILES_INI)
    except Exception:
        return None

    # Find the [Install...] section with a Default= key
    for section in config.sections():
        if section.startswith("Install"):
            default_path = config.get(section, "Default", fallback=None)
            if default_path:
                # Path is relative to ~/.config/zen
                abs_path = os.path.join(XDG_CONFIG_HOME, "zen", default_path)
                if os.path.isdir(abs_path):
                    return abs_path
    return None


def build_user_chrome_css(colors):
    """Build the userChrome.css content from palette colors.

    colors: dict with Material Design color keys (primary, onPrimary, etc.)
    """
    lines = [
        "/* GENERATED by scripts/repaint-zen.py from the odyssey palette.",
        "   Edits are lost at the next theme switch. Zen reads this at startup only. */",
        "",
        ":root {",
        f"  color-scheme: {colors['_mode']} !important;",
        f"  --zen-primary-color: {colors['primary']} !important;",
        f"  --zen-branding-bg: {colors['surface']} !important;",
        f"  --zen-branding-dark: {colors['surface']} !important;",
        f"  --zen-branding-paper: {colors['surface']} !important;",
        f"  --zen-branding-bg-reverse: {colors['onSurface']} !important;",
        f"  --zen-themed-toolbar-bg-transparent: {colors['surfaceContainer']} !important;",
        f"  --zen-dialog-background: {colors['surfaceContainer']} !important;",
        f"  --zen-in-content-dialog-background: {colors['surfaceContainer']} !important;",
        f"  --zen-urlbar-background: {colors['surfaceContainerHigh']} !important;",
        f"  --zen-colors-border: {colors['outlineVariant']} !important;",
        f"  --zen-input-border-color: {colors['outlineVariant']} !important;",
        f"  --toolbar-color: {colors['onSurface']} !important;",
        f"  --tab-selected-textcolor: {colors['onSurface']} !important;",
        f"  --lwt-text-color: {colors['onSurface']} !important;",
        # Zen picks its toolbar ink from each workspace's gradient, so a
        # light gradient gives dark text on our dark chrome. Pin it.
        f"  --toolbar-color-scheme: {colors['_mode']} !important;",
        f"  --toolbox-textcolor: {colors['onSurface']} !important;",
        f"  --toolbox-textcolor-inactive: {colors['onSurfaceVariant']} !important;",
        f"  --toolbar-field-color: {colors['onSurface']} !important;",
        f"  --toolbar-field-focus-color: {colors['onSurface']} !important;",
        f"  --sidebar-text-color: {colors['onSurface']} !important;",
        "}",
        "",
        # A light workspace gradient sets [zen-should-be-dark-mode=false],
        # which flips #browser to color-scheme: light (black tab titles).
        "#browser {",
        f"  color-scheme: {colors['_mode']} !important;",
        "}",
        "",
        ".tabbrowser-tab .tab-label, .zen-current-workspace-indicator-name {",
        f"  color: {colors['onSurface']} !important;",
        "}",
        "",
        "#zen-browser-background {",
        f"  --zen-main-browser-background: {colors['surface']} !important;",
        "}",
        "",
        "#zen-toolbar-background {",
        f"  --zen-main-browser-background-toolbar: {colors['surfaceContainerLow']} !important;",
        "}",
        "",
        ".tabbrowser-tab[selected] .tab-background {",
        f"  background-color: {colors['primaryContainer']} !important;",
        "}",
        "",
        ".tabbrowser-tab[selected] .tab-label {",
        f"  color: {colors['onPrimaryContainer']} !important;",
        "}",
        "",
        "#navigator-toolbox,",
        "#zen-sidebar-top-buttons,",
        ".tabbrowser-tab,",
        "#urlbar,",
        "menupopup {",
        "  font-family: 'Geist', sans-serif !important;",
        "}",
        "",
        "#urlbar-input {",
        "  font-family: 'Geist Mono', monospace !important;",
        "}",
    ]
    return "\n".join(lines) + "\n"


def write_atomic(path, content):
    """Write content to path atomically via temp file + rename."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    fd, tmp_path = tempfile.mkstemp(dir=os.path.dirname(path), text=True)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(content)
        os.replace(tmp_path, path)
    except Exception:
        try:
            os.unlink(tmp_path)
        except Exception:
            pass
        raise


def main():
    if len(sys.argv) < 2:
        sys.stderr.write(__doc__ + "\n")
        return 2

    palette_path = sys.argv[1]
    if not os.path.exists(palette_path):
        sys.stderr.write(f"palette file not found: {palette_path}\n")
        return 0

    zen_profile = resolve_zen_profile_path()
    if not zen_profile:
        sys.stderr.write("zen profile directory not found\n")
        return 0

    try:
        with open(palette_path, encoding="utf-8") as f:
            palette = json.load(f)
    except Exception as e:
        sys.stderr.write(f"failed to read palette: {e}\n")
        return 0

    # Follow the shell's Theme.effectiveMode: an explicit light/dark in
    # settings.json wins over the wallpaper-derived palette.mode.
    mode = palette.get("mode", "dark")
    state_home = os.environ.get("XDG_STATE_HOME") or os.path.expanduser("~/.local/state")
    try:
        with open(os.path.join(state_home, "odyssey", "settings.json"), encoding="utf-8") as f:
            forced = json.load(f)["settings"]["appearance"].get("mode")
        if forced in ("dark", "light"):
            mode = forced
    except Exception:
        pass
    material = palette.get(mode) or palette.get("dark") or palette.get("light")
    if not material:
        sys.stderr.write("palette JSON has neither a resolved mode nor dark/light\n")
        return 0

    # Inject mode into colors dict for the template
    colors = dict(material)
    colors["_mode"] = mode

    css_content = build_user_chrome_css(colors)
    css_path = os.path.join(zen_profile, "chrome", "userChrome.css")

    try:
        write_atomic(css_path, css_content)
    except Exception as e:
        sys.stderr.write(f"failed to write userChrome.css: {e}\n")
        return 0

    return 0


if __name__ == "__main__":
    sys.exit(main())
