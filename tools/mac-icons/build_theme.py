#!/usr/bin/env python3
"""Build the qml-rice-mac icon theme from picks.json (+ auto defaults).

Usage: build_theme.py [--target DIR] [--freeze] [--offline]
  --freeze   write the auto-resolved macOSicons choices into picks.json (so other machines match)
  --offline  never touch the network; failed/missing downloads fall back to the plated Papirus icon
"""
import argparse, os, shutil, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib, plate
from PIL import Image

THEME = "qml-rice-mac"

def resolve_pick(app, picks):
    p = picks.get(app["id"])
    if p and p.get("source") in ("papirus", "keep-papirus"):
        return {"source": "papirus"}
    if p and p.get("url"):
        return {"source": p.get("source", "url"), "url": p["url"], "sha256": p.get("sha256")}
    c = lib.candidates_for(app)          # auto = first candidate: official > itunes > macosicons
    if c:
        return {"source": c[0]["source"], "url": c[0]["url"], "sha256": c[0].get("sha256"), "name": c[0].get("appName"), "auto": True}
    return {"source": "papirus", "auto": True}

def master_for(app, pick, offline):
    os.makedirs(lib.MASTER_DIR, exist_ok=True)
    if pick["source"] != "papirus":
        try:
            dest = lib.url_cache_path(pick["url"])
            sha = pick.get("sha256")
            if pick["source"] == "official" and not sha:
                sha = next((e.get("sha256") for e in lib.lib_manifest().get("entries", []) if e["url"] == pick["url"]), None)
                if not sha:
                    raise ValueError("official pick has no pinned sha256")
            if offline and not os.path.exists(dest):
                raise OSError("offline")
            if offline:   # cache only: still integrity- and allowlist-checked, never touches the network
                if not lib.url_allowed(pick["url"], lib.ALL_IMAGE_HOSTS):
                    raise ValueError("refusing url")
                data = open(dest, "rb").read()
                if sha and lib._sha(data) != sha:
                    os.unlink(dest); raise ValueError("sha256 mismatch")
            else:
                lib.download(pick["url"], dest, sha256=sha)
            png = lib.to_png(dest)
            return (plate.mas_icon(png) if pick["source"] in ("itunes", "macosicons", "macosicons-official") else plate.fit_square(png)), pick["source"]
        except Exception as e:
            print("  ! %s: download failed (%s); using plated Papirus" % (app["id"], e))
    for n in lib.icon_names_for(app):
        src = lib.find_icon(n)
        if src:
            return plate.plate_icon(src), "plated"
    if (app.get("icon") or "").startswith("/") and os.path.exists(app["icon"]):
        try:
            return plate.plate_icon(app["icon"]), "plated"
        except Exception:
            pass
    return None, None

def index_theme():
    dirs = []
    sec = []
    for s in lib.SIZES:
        for sc in (1, 2):
            d = "%dx%d%s/apps" % (s, s, "@2x" if sc == 2 else "")
            dirs.append(d)
            sec.append("[%s]\nContext=Applications\nSize=%d\nScale=%d\nType=Fixed\n" % (d, s, sc))
    return ("[Icon Theme]\nName=%s\nComment=macOS-style app icons (generated by tools/mac-icons)\n"
            "Inherits=Papirus-Dark,Adwaita,hicolor\nDirectories=%s\n\n%s") % (THEME, ",".join(dirs), "\n".join(sec))

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--target", default=os.path.join(lib.HOME, ".local/share/icons", THEME))
    ap.add_argument("--freeze", action="store_true")
    ap.add_argument("--offline", action="store_true")
    a = ap.parse_args()
    apps = lib.load_apps()
    picks = lib.load_picks()
    tmp = a.target.rstrip("/") + ".building"
    shutil.rmtree(tmp, ignore_errors=True)
    os.makedirs(tmp)
    with open(os.path.join(tmp, "index.theme"), "w") as f:
        f.write(index_theme())
    stats = {"plated": 0, "none": 0}
    used = {}
    frozen = dict(picks)
    for app in apps:
        pick = resolve_pick(app, picks)
        master, kind = master_for(app, pick, a.offline)
        if master is None:
            stats["none"] += 1
            print("  - %s: no source icon found (left to inherited themes)" % app["id"])
            continue
        stats[kind] = stats.get(kind, 0) + 1
        if kind != "plated":
            used[app["id"]] = pick["source"]
        if a.freeze and pick.get("auto") and pick["source"] != "papirus":
            frozen[app["id"]] = {k: pick[k] for k in ("source", "url", "sha256") if pick.get(k)}
            frozen[app["id"]]["name"] = app["name"]
        names = lib.icon_names_for(app)
        if not names:
            continue
        for s in lib.SIZES:
            for sc in (1, 2):
                px = s * sc
                d = os.path.join(tmp, "%dx%d%s" % (s, s, "@2x" if sc == 2 else ""), "apps")
                os.makedirs(d, exist_ok=True)
                first = os.path.join(d, names[0] + ".png")
                master.resize((px, px), Image.LANCZOS).save(first, compress_level=3)
                for n in names[1:]:
                    link = os.path.join(d, n + ".png")
                    if os.path.lexists(link):
                        os.remove(link)
                    os.symlink(names[0] + ".png", link)
    if a.freeze:
        lib.save_json(lib.PICKS, frozen)
    old = a.target.rstrip("/") + ".old"
    shutil.rmtree(old, ignore_errors=True)
    if os.path.lexists(a.target):
        os.rename(a.target, old)
    os.rename(tmp, a.target)
    shutil.rmtree(old, ignore_errors=True)
    print("built %s: %s, %d plated Papirus, %d unresolved" %
          (a.target, ", ".join("%d %s" % (v, k) for k, v in sorted(stats.items()) if k not in ("plated", "none")), stats["plated"], stats["none"]))
    lib.save_json(os.path.join(lib.CACHE, "build-sources.json"), used)

main()
