#!/usr/bin/env bash
# Generates the Layer 6 web-app overlay files from tools/mac-webapps/webapps.json.
#
# Usage: gen.sh [OUT_ROOT]
#   OUT_ROOT defaults to the repo root. check.sh passes a temp dir and diffs
#   the result against the committed files.
#
# Per app <id>, writes:
#   dots/webapps/.local/bin/webapp-<id>            Brave --app launcher (own profile + class)
#   dots/webapps/.local/bin/webapp-<id>-toggle     show/hide overlay; launches if no window
#   dots/webapps/.local/share/applications/webapp-<id>.desktop
# And once, for all apps:
#   hypr/hyprland/webapps.lua                      window rules + toggle binds
#
# Needs: jq. Generated files are committed; never hand-edit them.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
OUT="${1:-$REPO}"
MANIFEST="$HERE/webapps.json"

command -v jq >/dev/null 2>&1 || { echo "gen.sh: jq is required" >&2; exit 1; }
[ -f "$MANIFEST" ] || { echo "gen.sh: missing $MANIFEST" >&2; exit 1; }
jq -e 'type == "array"' "$MANIFEST" >/dev/null || { echo "gen.sh: manifest must be a JSON array" >&2; exit 1; }

BIN_DIR="$OUT/dots/webapps/.local/bin"
APP_DIR="$OUT/dots/webapps/.local/share/applications"
LUA_OUT="$OUT/hypr/hyprland/webapps.lua"
mkdir -p "$BIN_DIR" "$APP_DIR" "$(dirname "$LUA_OUT")"

WARN="Generated by tools/mac-webapps/gen.sh from tools/mac-webapps/webapps.json. Do not edit."

lua_out="$(mktemp)"
trap 'rm -f "$lua_out"' EXIT
cat > "$lua_out" <<LUA
-- $WARN
-- Layer 6 web-app overlays (shell/docs/superpowers/specs/2026-10-12-macos-for-hyprland-design.md).
-- Each app: a floating, centred, sized window in special:webapp-<id>, plus a
-- toggle bind that runs ~/.local/bin/webapp-<id>-toggle.
-- Loaded from hyprland.lua after the glass blur. Add apps in webapps.json and re-run gen.sh.
LUA

count="$(jq 'length' "$MANIFEST")"
ids_seen=""
for ((i = 0; i < count; i++)); do
    entry="$(jq -c ".[$i]" "$MANIFEST")"
    id="$(jq -r '.id' <<<"$entry")"
    name="$(jq -r '.name' <<<"$entry")"
    url="$(jq -r '.url' <<<"$entry")"
    key="$(jq -r '.key' <<<"$entry")"
    size="$(jq -r '.size' <<<"$entry")"

    [[ "$id" =~ ^[a-z0-9][a-z0-9-]*$ ]] || { echo "gen.sh: bad id '$id' (lowercase, digits, dashes)" >&2; exit 1; }
    case " $ids_seen " in *" $id "*) echo "gen.sh: duplicate id '$id'" >&2; exit 1 ;; esac
    ids_seen="$ids_seen $id"
    [[ "$url" =~ ^https://[A-Za-z0-9._~:/?#@!$\&\(\)*+,\;=%-]+$ ]] || { echo "gen.sh: bad url for $id" >&2; exit 1; }
    [[ "$size" =~ ^([0-9]+)x([0-9]+)$ ]] || { echo "gen.sh: size for $id must be WIDTHxHEIGHT" >&2; exit 1; }
    w="${BASH_REMATCH[1]}"; h="${BASH_REMATCH[2]}"
    [ -n "$key" ] && [ "$key" != "null" ] || { echo "gen.sh: missing key for $id" >&2; exit 1; }

    host="${url#https://}"; host="${host%%/*}"
    path="${url#https://"$host"}"; path="${path%%\?*}"; path="${path%%#*}"; path="${path#/}"
    # Chromium derives the Wayland app_id of --app windows from host and path
    # (dots kept, '/' -> '_'); the rules also match webapp-<id>, which --class sets
    # (X11/XWayland). Both forms are matched, so either one works.
    slug_path="${path//\//_}"
    re_host="${host//./\\.}"
    CLASS_RE="^(webapp-${id}|brave-${re_host}__${slug_path}-.*)\$"
    # Single-quoted in shell (backslashes literal); escaped for the Lua string below.
    LUA_RE="$(printf '%s' "$CLASS_RE" | sed 's/\\/\\\\/g')"
    WS="special:webapp-${id}"

    # ---- launcher: Brave in app mode, own profile dir and class ----
    cat > "$BIN_DIR/webapp-$id" <<SH
#!/usr/bin/env bash
# $WARN
# $name as a Brave app window: own profile (not the main Brave profile) and class webapp-$id.
set -eu
command -v brave >/dev/null 2>&1 || { echo "webapp-$id: brave is not installed" >&2; exit 1; }
PROFILE="\$HOME/.local/share/qml-rice/webapps/$id"
mkdir -p "\$PROFILE"
exec brave --app='$url' --class=webapp-$id --user-data-dir="\$PROFILE" \\
    --no-first-run --no-default-browser-check
SH
    chmod 755 "$BIN_DIR/webapp-$id"

    # ---- toggle: hide/show the overlay, launch if no window exists ----
    cat > "$BIN_DIR/webapp-$id-toggle" <<SH
#!/usr/bin/env bash
# $WARN
# Shows/hides the $name overlay ($WS). Launches it when no window matches.
set -u
CLASS_RE='$CLASS_RE'
LAUNCHER="\$HOME/.local/bin/webapp-$id"
TOGGLE='hl.dsp.workspace.toggle_special("webapp-$id")'

has_window() {
    hyprctl clients -j 2>/dev/null | jq -e --arg re "\$CLASS_RE" \\
        'any(.[]; (.class // "") | test(\$re))' >/dev/null 2>&1
}

if ! has_window; then
    # The window rule parks the new window in $WS silently; wait for it, then reveal.
    "\$LAUNCHER" >/dev/null 2>&1 &
    for _ in \$(seq 1 100); do
        has_window && break
        sleep 0.1
    done
fi
hyprctl dispatch "\$TOGGLE" >/dev/null
SH
    chmod 755 "$BIN_DIR/webapp-$id-toggle"

    # ---- desktop entry (launcher menus; Icon from the Layer 2 theme when present) ----
    cat > "$APP_DIR/webapp-$id.desktop" <<DESK
[Desktop Entry]
# $WARN
Type=Application
Name=$name
Comment=$name as a floating web-app overlay
Exec=webapp-$id-toggle
Icon=webapp-$id
Terminal=false
Categories=Network;WebBrowser;
StartupNotify=false
StartupWMClass=webapp-$id
DESK

    # ---- Lua rules + bind ----
    cat >> "$lua_out" <<LUA

-- $name ($id)
do
    local cls = "$LUA_RE"
    hl.window_rule({ match = { class = cls }, float = true })
    hl.window_rule({ match = { class = cls }, workspace = "$WS silent" })
    hl.window_rule({ match = { class = cls }, size = { "$w", "$h" } })
    hl.window_rule({ match = { class = cls }, center = true })
    hl.bind("$key", hl.dsp.exec_cmd(HOME .. "/.local/bin/webapp-$id-toggle"),
        { description = "Web app: $name overlay" })
end
LUA
done

cp "$lua_out" "$LUA_OUT"
echo "gen.sh: wrote $count app(s) to $OUT"
