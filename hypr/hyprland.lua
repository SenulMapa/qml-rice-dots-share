-- This file sources other files in `hyprland` and `custom` folders
-- You wanna add your stuff in files in `custom`

-- Internal stuff --
require("hyprland.lib")
require("hyprland.services")

-- Environment variables --
require("hyprland.env")
if is_file_exists(HOME .. "/.config/hypr/custom/env.lua") then
    require("custom.env")
end

-- Default configurations --
require("hyprland.execs")
require("hyprland.general")
require("hyprland.rules")
require("hyprland.colors")
require("hyprland.keybinds")

-- Custom configurations --
if is_file_exists(HOME .. "/.config/hypr/custom/execs.lua") then
    require("custom.execs")
end
if is_file_exists(HOME .. "/.config/hypr/custom/general.lua") then
    require("custom.general")
end
if is_file_exists(HOME .. "/.config/hypr/custom/rules.lua") then
    require("custom.rules")
end
if is_file_exists(HOME .. "/.config/hypr/custom/keybinds.lua") then
    require("custom.keybinds")
end

-- nwg-displays support --
-- dofile, not require: require caches the module, so a `hyprctl reload`
-- after nwg-displays rewrites these files would silently keep the old layout.
if is_file_exists(HOME .. "/.config/hypr/workspaces.lua") then
    dofile(HOME .. "/.config/hypr/workspaces.lua")
end
if is_file_exists(HOME .. "/.config/hypr/monitors.lua") then
    dofile(HOME .. "/.config/hypr/monitors.lua")
end

-- Shell overrides --
require("hyprland.shellOverrides.main")
-- Glass blur, after the overrides so they cannot flatten it (see the file).
require("hyprland.glass")
-- Layer 6 web-app overlays (generated by tools/mac-webapps/gen.sh; loaded after the glass blur).
if is_file_exists(HOME .. "/.config/hypr/hyprland/webapps.lua") then
    require("hyprland.webapps")
end
-- Mission Control (F3 -> quickshell:missionControlToggle); see hyprland/mac-mission.lua.
if is_file_exists(HOME .. "/.config/hypr/hyprland/mac-mission.lua") then
    require("hyprland.mac-mission")
end
-- macOS window placement (macwm glue: float-by-default, per-workspace tiling) is OFF:
-- neither machine runs macwm (21 Oct). To try it, uncomment and start tools/macwm.
-- require("hyprland.mac-windows")
-- macOS layer 4 (master layout, Mac chrome/motion, traffic lights); must load last of the above.
require("hyprland.mac")

-- macOS Cmd-style keys (Super as Cmd) and trackpad gestures; each file has a
-- top-level ENABLED switch. Guarded by file existence like the optional files.
if is_file_exists(HOME .. "/.config/hypr/hyprland/mac-keys.lua") then
    require("hyprland.mac-keys")
end
if is_file_exists(HOME .. "/.config/hypr/hyprland/mac-gestures.lua") then
    require("hyprland.mac-gestures")
end

-- qml-rice keybinds (dropped in by install.sh at $HOME/.config/hypr/qml-rice-binds.lua).
-- Delete that file and this line to remove them; nothing else here is touched.
if is_file_exists(HOME .. "/.config/hypr/qml-rice-binds.lua") then
    dofile(HOME .. "/.config/hypr/qml-rice-binds.lua")
end

-- Per-machine extras, each loaded only if that machine has the file:
-- gaming.lua (desktop GPU/monitor fixes), openwhispr-binds.lua (dictation app).
for _, f in ipairs({ "gaming.lua", "openwhispr-binds.lua" }) do
    if is_file_exists(HOME .. "/.config/hypr/" .. f) then
        dofile(HOME .. "/.config/hypr/" .. f)
    end
end
